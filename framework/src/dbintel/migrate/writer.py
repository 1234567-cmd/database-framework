"""Write a plan to files. Nothing is applied."""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Union

from .generator import MigrationPlan, MigrationStep
from .safety import backup_recommendation, plan_hash

_WARNING = ("These are PROPOSALS generated by a tool. They have not been applied and must be reviewed and corrected by the "
            "people responsible for this database before use. Do not run them unchanged (MIG-007).")


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:50] or "step"


def _sql_comment(text: str) -> str:
    return "\n".join(f"-- {line}" for line in text.splitlines())


def _header(step: MigrationStep, direction: str) -> str:
    lines = [f"Step {step.id}: {step.title}", f"Direction: {direction}", f"Findings: {', '.join(step.finding_ids) or '(none)'}",
             f"Destructive: {step.destructive}. Reversible: {step.reversible}. Data loss risk: {step.data_loss_risk}. Lock risk: {step.lock_risk}.",
             "PROPOSAL ONLY. Review before use."]
    if not step.transactional:
        lines.append("Run statements individually, outside a transaction: this step contains non-transactional DDL.")
    if step.requires_backup:
        lines.append("Requires a verified backup first.")
    if step.requires_data_repair:
        lines.append("Requires data repair if the prechecks fail: " + "; ".join(step.data_repair_notes))
    for check in step.prechecks:
        lines.append(f"Precheck: {check.description}. Expect {check.expected}: {check.sql}")
    for note in step.online_notes:
        lines.append(f"Note: {note}")
    for risk in step.dependency_risks:
        lines.append(f"Dependency risk: {risk}")
    return _sql_comment("\n".join(lines))


def _manual_text(step: MigrationStep) -> str:
    return "\n".join([f"Step {step.id}: {step.title}", "MANUAL: this step has no generated SQL.", step.manual_description,
                      f"Findings: {', '.join(step.finding_ids) or '(none)'}"]) + "\n"


def _readme(plan: MigrationPlan) -> str:
    rows = "\n".join(f"| {s.order:04d} | {s.id} | {s.title} | {'manual' if s.manual else 'sql'} | {s.destructive} | {s.reversible} |"
                     for s in plan.steps)
    manual = "\n".join(f"- {s.id}: {s.manual_description}" for s in plan.manual_steps) or "- None."
    return f"""# Migration proposal for {plan.database}

**Warning:** {_WARNING}

Target dialect: {plan.dialect}. Plan hash: `{plan_hash(plan)}`.

## Back up first

{backup_recommendation(plan.dialect)}

Run steps in numeric order. Use each `.up.sql` only after its prechecks pass. The `.down.sql` files are rollbacks; where a step cannot be reversed without loss, the file says so and contains no statements.

## Steps

| Order | Id | Title | Type | Destructive | Reversible |
|---|---|---|---|---|---|
{rows}

## Manual steps

{manual}

## Notes

{chr(10).join('- ' + n for n in plan.notes) or '- None.'}
"""


def write_migration_files(plan: MigrationPlan, out_dir: Union[str, Path]) -> list[Path]:
    """Write ``NNNN_<slug>.up.sql``, ``.down.sql`` (or ``.manual.txt``), ``plan.json`` and ``README.md``."""
    base = Path(out_dir)
    base.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for step in sorted(plan.steps, key=lambda s: s.order):
        stem = f"{step.order:04d}_{_slug(step.title)}"
        if step.manual:
            path = base / f"{stem}.manual.txt"
            path.write_text(_manual_text(step), encoding="utf-8")
            written.append(path)
            continue
        up = base / f"{stem}.up.sql"
        up.write_text(_header(step, "up") + "\n" + step.up_script + "\n", encoding="utf-8")
        down = base / f"{stem}.down.sql"
        if step.reversible and step.down_sql:
            body = step.down_script + "\n"
        else:
            body = _sql_comment(f"NOT REVERSIBLE WITHOUT LOSS: {step.irreversible_reason or 'no rollback exists for this step.'}") + "\n"
        down.write_text(_header(step, "down") + "\n" + body, encoding="utf-8")
        written += [up, down]
    plan_path = base / "plan.json"
    plan_path.write_text(json.dumps({"plan_hash": plan_hash(plan), **plan.to_dict()}, indent=2, sort_keys=True, default=str), encoding="utf-8")
    readme = base / "README.md"
    readme.write_text(_readme(plan), encoding="utf-8")
    return written + [plan_path, readme]
